// ===================================
// 録画開始
// 選手移動履歴を保存
// ===================================

function startRecording(){

  // これまで保存されていた録画データを削除する
  recordings = [];

  // 録画中であることを記録する
  isRecording = true;

  // 録画開始のメッセージを表示する
  alert("録画開始");

}


// ===================================
// 録画停止
// ===================================

function stopRecording(){

  // 録画中の状態を終了する
  isRecording = false;

  // 録画停止のメッセージを表示する
  alert("録画停止");

  // 保存された録画データをコンソールに表示する
  // 開発中の動作確認に使用する
  console.log(recordings);

}


// ===================================
// 録画再生
// 保存された移動履歴を再生
// ===================================

function playRecording(){

  // 保存されている録画データを順番に処理する
  recordings.forEach((record,index)=>{

    // 録画データを順番に再生するため、時間をずらして実行する
    setTimeout(()=>{

      // 記録されている位置まで選手を移動させる
      record.player.to({

        // 移動先のX座標
        x:record.x,

        // 移動先のY座標
        y:record.y,

        // 選手が移動する時間
        duration:0.03

      });

    // indexの値に応じて、再生するタイミングを30ミリ秒ずつずらす
    }, index * 30);

  });

}